const TILE = 24;
const MAP_SIZE = 26;

const TILE_EMPTY = 0;
const TILE_BRICK = 1;
const TILE_STEEL = 2;
const TILE_GRASS = 3;
const TILE_WATER = 4;
const TILE_BASE = 5;
const TILE_BASE_DEAD = 6;

const CHAR_TILE = {
  ".": TILE_EMPTY,
  "#": TILE_BRICK,
  "@": TILE_STEEL,
  ",": TILE_GRASS,
  "~": TILE_WATER,
  B: TILE_BASE,
  P: TILE_EMPTY,
  E: TILE_EMPTY,
};

function normalizeRow(row) {
  const cells = (row || "").slice(0, MAP_SIZE);
  return cells.padEnd(MAP_SIZE, ".");
}

function parseMap(name, subtitle, rows) {
  const normalized = Array.from({ length: MAP_SIZE }, (_, y) => normalizeRow(rows[y]));
  const grid = [];
  const enemySpawns = [];
  let playerSpawn = { x: 12 * TILE, y: 24 * TILE };

  for (let y = 0; y < MAP_SIZE; y++) {
    const row = normalized[y];
    const tiles = [];
    for (let x = 0; x < MAP_SIZE; x++) {
      const ch = row[x];
      tiles.push(CHAR_TILE[ch] ?? TILE_EMPTY);
      if (ch === "P") playerSpawn = { x: x * TILE, y: y * TILE };
      if (ch === "E") enemySpawns.push({ x: x * TILE, y: y * TILE });
    }
    grid.push(tiles);
  }

  if (enemySpawns.length === 0) {
    enemySpawns.push({ x: TILE, y: TILE }, { x: 12 * TILE, y: TILE }, { x: 23 * TILE, y: TILE });
  }

  return { name, subtitle, grid, playerSpawn, enemySpawns };
}

